#!/usr/bin/env node
// Scans src/**/*.ts for literal process.env references and writes the
// generated registry consumed by src/config/env-typo-guard.ts.
// Regenerated automatically by `npm run build` (prebuild) — never hand-edit
// src/config/known-env-vars.generated.ts.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const SRC_ROOT = join(process.cwd(), 'src');
const OUT_FILE = join(SRC_ROOT, 'config', 'known-env-vars.generated.ts');

const DOT_PATTERN = /process\.env\.([A-Za-z_][A-Za-z0-9_]*)/g;
const BRACKET_PATTERN = /process\.env\[\s*['"]([A-Za-z_][A-Za-z0-9_]*)['"]\s*\]/g;

function walk(dir, out) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      walk(full, out);
    } else if (entry.endsWith('.ts') || entry.endsWith('.tsx')) {
      out.push(full);
    }
  }
}

const files = [];
walk(SRC_ROOT, files);

const names = new Set();
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(DOT_PATTERN)) names.add(m[1]);
  for (const m of text.matchAll(BRACKET_PATTERN)) names.add(m[1]);
}

const sorted = [...names].sort();

const header = `// AUTO-GENERATED by scripts/generate-env-registry.mjs — do not edit by hand.
// Regenerated on every \`npm run build\` (prebuild). Statically discovered
// from literal \`process.env.NAME\` / \`process.env['NAME']\` reads under src/.
// Dynamically-composed names (e.g. \`process.env[\`\${x}_API_KEY\`]\`) are not
// captured and will not be typo-checked — that is a known, accepted gap.
//
// Newline-delimited template string, not a JSON array: a sorted list of
// ALL_CAPS names quoted one-per-line (e.g. "..._KEY",\\n  "...") reliably
// false-positives gitleaks' generic-api-key rule, which treats an adjacent
// quoted-name/quoted-string pair as a key/value assignment.
`;

const body = `export const KNOWN_ENV_VARS: readonly string[] = \`\n${sorted.join('\n')}\n\`.trim().split('\\n');\n`;

writeFileSync(OUT_FILE, header + body);
console.log(`[env-registry] wrote ${sorted.length} known env var names from ${files.length} files under src/ -> ${relative(process.cwd(), OUT_FILE)}`);
