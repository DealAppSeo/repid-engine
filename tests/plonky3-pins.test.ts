/**
 * ZKP Invariant 5 checker (scripts/zkp/plonky3-pins.cjs). The checker must be able to say FAIL
 * and NOT_CHECKED, not only PASS (LESSONS 5), so each verdict has a case here.
 */
import * as fs from 'fs';
import * as path from 'path';

// eslint-disable-next-line @typescript-eslint/no-var-requires
const { plonky3Sources, check } = require('../scripts/zkp/plonky3-pins.cjs');

const GIT_A = 'git+https://github.com/Plonky3/Plonky3?rev=27d59f7350daf6b02d11b01c3a55af453554b515#27d59f7350daf6b02d11b01c3a55af453554b515';
const GIT_B = 'git+https://github.com/Plonky3/Plonky3.git#6374a36ff50fc641821513852263cc61ca7a1278';
const REG = 'registry+https://github.com/rust-lang/crates.io-index';

const pkg = (name: string, version: string, source?: string) =>
  `[[package]]\nname = "${name}"\nversion = "${version}"\n${source ? `source = "${source}"\n` : ''}\n`;
const lock = (...pkgs: string[]) => `# This file is automatically @generated by Cargo.\nversion = 4\n\n${pkgs.join('')}`;

const onA = lock(pkg('p3-field', '0.5.1', GIT_A), pkg('p3-fri', '0.5.1', GIT_A), pkg('serde', '1.0.0', REG));

describe('plonky3Sources', () => {
  it('collapses every p3 crate from one commit to one source and ignores other crates', () => {
    expect(plonky3Sources(onA)).toEqual(['git:27d59f7350daf6b02d11b01c3a55af453554b515']);
  });

  it('reads an exact rev pin from a Cargo.toml as the same key a lockfile gives', () => {
    const toml = '[dependencies]\np3-field = { git = "https://github.com/Plonky3/Plonky3", rev = "27d59f7350daf6b02d11b01c3a55af453554b515" }\nserde = "1"\n';
    expect(plonky3Sources(toml)).toEqual(plonky3Sources(onA));
  });

  it('marks a Cargo.toml version range or rev-less git dep as unpinned', () => {
    const toml = 'p3-air = "0.3.0"\np3-fri = { git = "https://github.com/Plonky3/Plonky3.git" }\n';
    expect(plonky3Sources(toml)).toEqual(['unpinned:p3-air', 'unpinned:p3-fri']);
  });

  it('labels crates.io releases by version', () => {
    expect(plonky3Sources(lock(pkg('p3-air', '0.3.0', REG)))).toEqual(['crates.io@0.3.0']);
  });

  it('treats a path dependency (no source line) as its own pin rather than skipping it', () => {
    expect(plonky3Sources(lock(pkg('p3-air', '0.5.1')))).toEqual(['path@0.5.1']);
  });

  it('parses the real zkp-vault lockfile (positive control on the real format)', () => {
    const real = fs.readFileSync(path.join(__dirname, '..', 'zkp-vault', 'Cargo.lock'), 'utf8');
    // Pins today's state: crates.io 0.3.0. When plan step B2 moves the vault to the live
    // prover's commit, this expectation changes in the same PR.
    expect(plonky3Sources(real)).toEqual(['crates.io@0.3.0']);
  });
});

describe('check', () => {
  it('PASS when a lockfile and a rev-pinned manifest name the same commit', () => {
    const toml = 'p3-uni-stark = { git = "https://github.com/Plonky3/Plonky3", rev = "27d59f7350daf6b02d11b01c3a55af453554b515" }\n';
    expect(check([{ file: 'lock', text: onA }, { file: 'toml', text: toml }]).verdict).toBe('PASS');
  });

  it('NOT_CHECKED, never PASS, when a manifest dep is not pinned to a commit', () => {
    const r = check([{ file: 'lock', text: onA }, { file: 'toml', text: 'p3-fri = { git = "https://github.com/Plonky3/Plonky3.git" }\n' }]);
    expect(r.verdict).toBe('NOT_CHECKED');
  });

  it('PASS when every lockfile resolves to the same single source', () => {
    const r = check([{ file: 'a', text: onA }, { file: 'b', text: onA }]);
    expect(r.verdict).toBe('PASS');
  });

  it('FAIL when two lockfiles build different commits (negative control)', () => {
    const r = check([{ file: 'a', text: onA }, { file: 'b', text: lock(pkg('p3-field', '0.5.1', GIT_B)) }]);
    expect(r.verdict).toBe('FAIL');
    expect(r.distinct).toHaveLength(2);
  });

  it('FAIL when one lockfile mixes crates.io and git', () => {
    const r = check([{ file: 'a', text: lock(pkg('p3-field', '0.3.0', REG), pkg('p3-fri', '0.5.1', GIT_A)) }]);
    expect(r.verdict).toBe('FAIL');
  });

  it('NOT_CHECKED, never PASS, when a lockfile is unreadable', () => {
    const r = check([{ file: 'a', text: onA }, { file: 'missing', text: null }]);
    expect(r.verdict).toBe('NOT_CHECKED');
  });

  it('NOT_CHECKED when a listed lockfile holds no Plonky3 crate', () => {
    const r = check([{ file: 'a', text: onA }, { file: 'b', text: lock(pkg('serde', '1.0.0', REG)) }]);
    expect(r.verdict).toBe('NOT_CHECKED');
  });

  it('FAIL outranks NOT_CHECKED: a known split is reported even if another file is unread', () => {
    const r = check([
      { file: 'a', text: onA },
      { file: 'b', text: lock(pkg('p3-field', '0.3.0', REG)) },
      { file: 'missing', text: null },
    ]);
    expect(r.verdict).toBe('FAIL');
  });
});
